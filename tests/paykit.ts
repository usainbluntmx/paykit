import * as anchor from "@coral-xyz/anchor";
import { Program } from "@coral-xyz/anchor";
import { Keypair, LAMPORTS_PER_SOL, PublicKey } from "@solana/web3.js";
import { assert } from "chai";
import * as fs from "fs";
import * as path from "path";

// BN is not a detectable named export when mocha loads this file as an ES module
const BN: any = (anchor as any).BN ?? (anchor as any).default?.BN;

// ─── Contract tests (local validator) ─────────────────────────────────────────
// Run with:  anchor test
// Known-bug tests (currently failing on purpose) run with:  KNOWN_BUGS=1 anchor test

const CAP_PAY_AGENTS = 1 << 0;
const CAP_HIRE_BASIC = 1 << 1;
const CAP_HIRE_STANDARD = 1 << 2;
const CAP_HIRE_PREMIUM = 1 << 3;
const CAP_TRANSFER_SOL = 1 << 4;
const CAP_TRANSFER_SPL = 1 << 5;
const CAP_ALL_DEFAULT = 127; // bits 0-6

describe("paykit contract", () => {
  const provider = anchor.AnchorProvider.env();
  anchor.setProvider(provider);
  // Use the patched IDL (same one the SDK ships): the one generated by `anchor build`
  // does not expose the AgentAccount account type, so program.account.* is undefined.
  const idl = JSON.parse(
    fs.readFileSync(path.join(process.cwd(), "sdk/idl/paykit.json"), "utf8")
  );
  const program = new Program(idl, provider) as Program<any>;
  const owner = provider.wallet.publicKey;
  const RUN = Date.now().toString(36).slice(-6);

  let counter = 0;
  const uniqueName = (prefix: string) => `${prefix}-${RUN}-${counter++}`;

  const agentPda = (agentKey: PublicKey, name: string) =>
    PublicKey.findProgramAddressSync(
      [Buffer.from("agent"), agentKey.toBuffer(), Buffer.from(name)],
      program.programId
    )[0];

  interface Opts {
    spendLimit?: number;
    bps?: number;
    funding?: number;
    caps?: number;
    tier?: number;
  }

  async function register(prefix: string, o: Opts = {}) {
    const kp = Keypair.generate();
    const name = uniqueName(prefix);
    const pda = agentPda(kp.publicKey, name);
    await program.methods
      .registerAgent(
        name,
        new BN(o.spendLimit ?? 1_000_000),
        o.bps ?? 10000,
        new BN(o.funding ?? 0),
        o.caps ?? CAP_ALL_DEFAULT,
        o.tier ?? 0
      )
      .accountsPartial({ agent: pda, agentSigner: kp.publicKey, owner })
      .rpc();
    return { kp, name, pda };
  }

  const pay = (
    a: { kp: Keypair; pda: PublicKey },
    amount: number,
    memo = "test",
    category = 0,
    signer: Keypair = a.kp
  ) =>
    program.methods
      .recordPayment(new BN(amount), Keypair.generate().publicKey, memo, category)
      .accountsPartial({ agent: a.pda, agentSigner: signer.publicKey })
      .signers([signer])
      .rpc();

  const a2a = (
    sender: { kp: Keypair; pda: PublicKey },
    receiver: { pda: PublicKey },
    amount: number,
    signer: Keypair = sender.kp
  ) =>
    program.methods
      .agentToAgentPayment(new BN(amount), "service", 0)
      .accountsPartial({
        senderAgent: sender.pda,
        receiverAgent: receiver.pda,
        agentSigner: signer.publicKey,
      })
      .signers([signer])
      .rpc();

  async function expectError(p: Promise<unknown>, code: string) {
    try {
      await p;
    } catch (e: any) {
      const got =
        e?.error?.errorCode?.code ?? e?.message?.match(/Error Code: (\w+)/)?.[1];
      assert.equal(got, code, `expected ${code}, got ${got}: ${e?.message}`);
      return;
    }
    assert.fail(`expected ${code} but the transaction succeeded`);
  }

  async function expectAnyError(p: Promise<unknown>, what: string) {
    try {
      await p;
    } catch {
      return;
    }
    assert.fail(`expected failure (${what}) but the transaction succeeded`);
  }

  const fetch = (pda: PublicKey) => program.account.agentAccount.fetch(pda);

  // ─── register_agent ─────────────────────────────────────────────────────────

  describe("register_agent", () => {
    it("stores the configuration and funds the agent wallet", async () => {
      const a = await register("reg", {
        spendLimit: 5_000_000,
        bps: 2500,
        funding: 0.01 * LAMPORTS_PER_SOL,
        caps: CAP_PAY_AGENTS,
        tier: 1,
      });
      const acc = await fetch(a.pda);
      assert.equal(acc.agentKey.toBase58(), a.kp.publicKey.toBase58());
      assert.equal(acc.owner.toBase58(), owner.toBase58());
      assert.equal(acc.name, a.name);
      assert.equal(acc.spendLimit.toNumber(), 5_000_000);
      assert.equal(acc.dailyLimitBps, 2500);
      assert.equal(acc.capabilities, CAP_PAY_AGENTS);
      assert.equal(acc.tier, 1);
      assert.isTrue(acc.isActive);
      assert.equal(acc.totalSpent.toNumber(), 0);
      assert.equal(acc.paymentCount.toNumber(), 0);

      const now = Math.floor(Date.now() / 1000);
      const days = (acc.expiresAt.toNumber() - now) / 86400;
      assert.isAbove(days, 364);
      assert.isBelow(days, 366);

      const bal = await provider.connection.getBalance(a.kp.publicKey);
      assert.equal(bal, 0.01 * LAMPORTS_PER_SOL);
    });

    it("rejects invalid parameters", async () => {
      const bad = async (o: Opts, code: string) => {
        const kp = Keypair.generate();
        const name = uniqueName("bad");
        await expectError(
          program.methods
            .registerAgent(
              name,
              new BN(o.spendLimit ?? 1000),
              o.bps ?? 5000,
              new BN(0),
              CAP_ALL_DEFAULT,
              o.tier ?? 0
            )
            .accountsPartial({
              agent: agentPda(kp.publicKey, name),
              agentSigner: kp.publicKey,
              owner,
            })
            .rpc(),
          code
        );
      };
      await bad({ spendLimit: 0 }, "InvalidSpendLimit");
      await bad({ bps: 0 }, "InvalidDailyLimit");
      await bad({ bps: 10001 }, "InvalidDailyLimit");
      await bad({ tier: 3 }, "InvalidTier");
    });

    it("cannot register the same (agent key, name) twice", async () => {
      const a = await register("dup");
      await expectAnyError(
        program.methods
          .registerAgent(a.name, new BN(1000), 5000, new BN(0), CAP_ALL_DEFAULT, 0)
          .accountsPartial({ agent: a.pda, agentSigner: a.kp.publicKey, owner })
          .rpc(),
        "duplicate registration"
      );
    });
  });

  // ─── Authentication (SEC-001 regression) ────────────────────────────────────

  describe("authentication of the agent signer", () => {
    it("record_payment: the legitimate agent key can pay", async () => {
      const a = await register("auth-ok");
      await pay(a, 1000);
      const acc = await fetch(a.pda);
      assert.equal(acc.totalSpent.toNumber(), 1000);
      assert.equal(acc.paymentCount.toNumber(), 1);
      assert.equal(acc.dailySpent.toNumber(), 1000);
    });

    it("record_payment: a foreign signer is rejected (UnauthorizedSigner)", async () => {
      const victim = await register("victim");
      const attacker = Keypair.generate();
      await expectError(pay(victim, 1000, "steal", 0, attacker), "UnauthorizedSigner");
      const acc = await fetch(victim.pda);
      assert.equal(acc.totalSpent.toNumber(), 0, "victim state must not change");
    });

    it("record_payment: even the owner wallet cannot sign as the agent", async () => {
      const victim = await register("owner-as-agent");
      const wallet = (provider.wallet as anchor.Wallet).payer;
      await expectError(pay(victim, 1000, "x", 0, wallet), "UnauthorizedSigner");
    });

    it("agent_to_agent_payment: legitimate sender works and counters update", async () => {
      const sender = await register("a2a-s");
      const receiver = await register("a2a-r");
      await a2a(sender, receiver, 2000);
      const s = await fetch(sender.pda);
      const r = await fetch(receiver.pda);
      assert.equal(s.totalSpent.toNumber(), 2000);
      assert.equal(s.paymentCount.toNumber(), 1);
      assert.equal(r.paymentCount.toNumber(), 1);
      assert.equal(r.totalSpent.toNumber(), 0);
    });

    it("agent_to_agent_payment: a foreign signer cannot spend from the sender", async () => {
      const victim = await register("a2a-victim");
      const receiver = await register("a2a-rcv");
      const attacker = Keypair.generate();
      await expectError(a2a(victim, receiver, 1000, attacker), "UnauthorizedSigner");
      const acc = await fetch(victim.pda);
      assert.equal(acc.totalSpent.toNumber(), 0);
    });

    it("agent_to_agent_payment: the receiver's key cannot sign for the sender", async () => {
      const victim = await register("a2a-v2");
      const receiver = await register("a2a-r2");
      await expectError(a2a(victim, receiver, 1000, receiver.kp), "UnauthorizedSigner");
    });
  });

  // ─── Limits ─────────────────────────────────────────────────────────────────

  describe("limits and validations in record_payment", () => {
    it("rejects amount 0 and memo > 64 chars", async () => {
      const a = await register("val");
      await expectError(pay(a, 0), "InvalidAmount");
      await expectError(pay(a, 1, "x".repeat(65)), "MemoTooLong");
      await pay(a, 1, "x".repeat(64)); // boundary ok
    });

    it("enforces the total spend limit (boundary inclusive)", async () => {
      const a = await register("total", { spendLimit: 10_000 });
      await pay(a, 10_000);
      await expectError(pay(a, 1), "SpendLimitExceeded");
    });

    it("enforces the daily limit (bps of spend_limit)", async () => {
      // 10% of 1_000_000 = 100_000 per day
      const a = await register("daily", { spendLimit: 1_000_000, bps: 1000 });
      await expectError(pay(a, 100_001), "DailyLimitExceeded");
      await pay(a, 100_000);
      await expectError(pay(a, 1), "DailyLimitExceeded");
    });

    it("enforces the category limit per payment", async () => {
      const a = await register("cat");
      await program.methods
        .setCategoryLimit(1, new BN(50_000), null)
        .accountsPartial({ agent: a.pda, owner })
        .rpc();
      await expectError(pay(a, 50_001, "x", 1), "CategoryLimitExceeded");
      await pay(a, 50_000, "x", 1);
      await pay(a, 60_000, "x", 2); // category without limit is unrestricted
    });

    it("set_category_limit rejects category 0", async () => {
      const a = await register("cat0");
      await expectError(
        program.methods
          .setCategoryLimit(0, new BN(1), null)
          .accountsPartial({ agent: a.pda, owner })
          .rpc(),
        "InvalidCategory"
      );
    });

    it("blocks payments while inactive and allows them after reactivation", async () => {
      const a = await register("inactive");
      await program.methods.deactivateAgent().accountsPartial({ agent: a.pda, owner }).rpc();
      await expectError(pay(a, 1000), "AgentInactive");
      await program.methods.reactivateAgent().accountsPartial({ agent: a.pda, owner }).rpc();
      await pay(a, 1000);
    });
  });

  describe("record_payment capabilities", () => {
    it("requires a transfer capability (SOL or SPL)", async () => {
      const none = await register("cap-none", { caps: 0 });
      await expectError(pay(none, 1000), "CapabilityDenied");
      const onlyA2A = await register("cap-a2a", { caps: CAP_PAY_AGENTS });
      await expectError(pay(onlyA2A, 1000), "CapabilityDenied");
      const sol = await register("cap-sol", { caps: CAP_TRANSFER_SOL });
      await pay(sol, 1000);
      const spl = await register("cap-spl", { caps: CAP_TRANSFER_SPL });
      await pay(spl, 1000);
    });
  });

  // ─── agent_to_agent_payment: capabilities and tiers ─────────────────────────

  describe("agent_to_agent_payment rules", () => {
    it("requires CAP_PAY_AGENTS", async () => {
      const s = await register("nocap-s", { caps: CAP_HIRE_BASIC });
      const r = await register("nocap-r");
      await expectError(a2a(s, r, 1000), "CapabilityDenied");
    });

    it("requires the hire capability matching the receiver tier", async () => {
      const s = await register("tier-s", { caps: CAP_PAY_AGENTS | CAP_HIRE_BASIC });
      const basic = await register("tier-r0", { tier: 0 });
      const standard = await register("tier-r1", { tier: 1 });
      const premium = await register("tier-r2", { tier: 2 });
      await a2a(s, basic, 1000);
      await expectError(a2a(s, standard, 1000), "TierNotAllowed");
      await expectError(a2a(s, premium, 1000), "TierNotAllowed");

      const s2 = await register("tier-s2", {
        caps: CAP_PAY_AGENTS | CAP_HIRE_STANDARD | CAP_HIRE_PREMIUM,
      });
      await a2a(s2, standard, 1000);
      await a2a(s2, premium, 1000);
      await expectError(a2a(s2, basic, 1000), "TierNotAllowed");
    });

    it("rejects paying itself (SelfPayment)", async () => {
      const a = await register("self");
      await expectError(a2a(a, a, 1000), "SelfPayment");
      const acc = await fetch(a.pda);
      assert.equal(acc.totalSpent.toNumber(), 0);
      assert.equal(acc.paymentCount.toNumber(), 0);
    });

    it("rejects an inactive receiver", async () => {
      const s = await register("inrcv-s");
      const r = await register("inrcv-r");
      await program.methods.deactivateAgent().accountsPartial({ agent: r.pda, owner }).rpc();
      await expectError(a2a(s, r, 1000), "AgentInactive");
    });

    it("enforces the sender's total and daily limits", async () => {
      const s = await register("a2a-lim", { spendLimit: 10_000, bps: 5000 });
      const r = await register("a2a-lim-r");
      await expectError(a2a(s, r, 5_001), "DailyLimitExceeded");
      await a2a(s, r, 5_000);
      await expectError(a2a(s, r, 1), "DailyLimitExceeded");
    });
  });

  // ─── Owner operations ───────────────────────────────────────────────────────

  describe("owner operations", () => {
    it("rejects owner-only instructions from a non-owner (ConstraintHasOne)", async () => {
      const a = await register("own-auth");
      const attacker = Keypair.generate();
      await expectError(
        program.methods
          .setCapabilities(0xffff)
          .accountsPartial({ agent: a.pda, owner: attacker.publicKey })
          .signers([attacker])
          .rpc(),
        "ConstraintHasOne"
      );
      await expectError(
        program.methods
          .updateSpendLimit(new BN(999_999_999))
          .accountsPartial({ agent: a.pda, owner: attacker.publicKey })
          .signers([attacker])
          .rpc(),
        "ConstraintHasOne"
      );
      const acc = await fetch(a.pda);
      assert.equal(acc.capabilities, CAP_ALL_DEFAULT);
      assert.equal(acc.spendLimit.toNumber(), 1_000_000);
    });

    it("set_capabilities, set_tier and update_spend_limit", async () => {
      const a = await register("own-ok");
      await program.methods.setCapabilities(CAP_TRANSFER_SOL).accountsPartial({ agent: a.pda, owner }).rpc();
      await program.methods.setTier(2).accountsPartial({ agent: a.pda, owner }).rpc();
      await program.methods.updateSpendLimit(new BN(42)).accountsPartial({ agent: a.pda, owner }).rpc();
      const acc = await fetch(a.pda);
      assert.equal(acc.capabilities, CAP_TRANSFER_SOL);
      assert.equal(acc.tier, 2);
      assert.equal(acc.spendLimit.toNumber(), 42);

      await expectError(
        program.methods.setTier(3).accountsPartial({ agent: a.pda, owner }).rpc(),
        "InvalidTier"
      );
      await expectError(
        program.methods.updateSpendLimit(new BN(0)).accountsPartial({ agent: a.pda, owner }).rpc(),
        "InvalidSpendLimit"
      );
    });

    it("update_spend_limit cannot go below total_spent (SpendLimitBelowSpent)", async () => {
      const a = await register("limit-floor", { spendLimit: 10_000 });
      await pay(a, 8_000);
      await expectError(
        program.methods.updateSpendLimit(new BN(7_999)).accountsPartial({ agent: a.pda, owner }).rpc(),
        "SpendLimitBelowSpent"
      );
      // exactly total_spent is allowed (boundary inclusive)
      await program.methods.updateSpendLimit(new BN(8_000)).accountsPartial({ agent: a.pda, owner }).rpc();
      const acc = await fetch(a.pda);
      assert.equal(acc.spendLimit.toNumber(), 8_000);
      await expectError(pay(a, 1), "SpendLimitExceeded");
    });

    it("set_custom_capability toggles bits 8-15 and validates the slot", async () => {
      const a = await register("custom", { caps: 0 });
      await program.methods
        .setCustomCapability(0, "translate", true)
        .accountsPartial({ agent: a.pda, owner })
        .rpc();
      await program.methods
        .setCustomCapability(7, "audit", true)
        .accountsPartial({ agent: a.pda, owner })
        .rpc();
      let acc = await fetch(a.pda);
      assert.equal(acc.capabilities, (1 << 8) | (1 << 15));
      await program.methods
        .setCustomCapability(0, "translate", false)
        .accountsPartial({ agent: a.pda, owner })
        .rpc();
      acc = await fetch(a.pda);
      assert.equal(acc.capabilities, 1 << 15);
      await expectError(
        program.methods
          .setCustomCapability(8, "nope", true)
          .accountsPartial({ agent: a.pda, owner })
          .rpc(),
        "InvalidCapabilitySlot"
      );
    });

    it("renew_agent extends the expiry and rejects non-positive extensions", async () => {
      const a = await register("renew");
      const before = (await fetch(a.pda)).expiresAt.toNumber();
      await program.methods.renewAgent(new BN(1000)).accountsPartial({ agent: a.pda, owner }).rpc();
      const after = (await fetch(a.pda)).expiresAt.toNumber();
      assert.equal(after - before, 1000);
      await expectError(
        program.methods.renewAgent(new BN(0)).accountsPartial({ agent: a.pda, owner }).rpc(),
        "InvalidSpendLimit"
      );
    });

    it("renew_agent rejects an extension that overflows the expiry (MathOverflow)", async () => {
      const a = await register("renew-ovf");
      await expectError(
        program.methods
          .renewAgent(new BN("9223372036854775807"))
          .accountsPartial({ agent: a.pda, owner })
          .rpc(),
        "MathOverflow"
      );
    });

    it("close_agent returns the rent to the owner and deletes the account", async () => {
      const a = await register("close");
      const before = await provider.connection.getBalance(owner);
      await program.methods.closeAgent().accountsPartial({ agent: a.pda, owner }).rpc();
      const after = await provider.connection.getBalance(owner);
      assert.isAbove(after, before, "owner should recover rent (minus the tx fee)");
      assert.isNull(await program.account.agentAccount.fetchNullable(a.pda));
    });

    it("close_agent from a non-owner is rejected", async () => {
      const a = await register("close-bad");
      const attacker = Keypair.generate();
      await expectError(
        program.methods
          .closeAgent()
          .accountsPartial({ agent: a.pda, owner: attacker.publicKey })
          .signers([attacker])
          .rpc(),
        "ConstraintHasOne"
      );
      assert.isNotNull(await program.account.agentAccount.fetchNullable(a.pda));
    });
  });

  // ─── Known contract bugs ────────────────────────────────────────────────────
  // These tests describe the DESIRED behavior and currently FAIL against the
  // deployed program. They are skipped unless KNOWN_BUGS=1, so `anchor test` and
  // CI stay green. When a bug is fixed, move its test into the sections above.

  const knownBug = process.env.KNOWN_BUGS === "1" ? it : it.skip;

  // (no known bugs at the moment — add them here as `knownBug(...)` tests)
});